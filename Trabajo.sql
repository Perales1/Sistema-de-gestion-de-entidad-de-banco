-- 19. Clientes cuyo saldo total en todas sus cuentas es mayor al saldo medio de todas las cuentas del banco --
SELECT c.cod_cliente, c.nombre, c.apellidos,
       (SELECT SUM(cu.saldo)
        FROM CLIENTE_CUENTA cc2, CUENTA cu
        WHERE cc2.cod_cliente = c.cod_cliente AND cc2.cod_cuenta = cu.cod_cuenta
       ) AS saldo_total
FROM CLIENTE c
WHERE (SELECT SUM(cu.saldo)
       FROM CLIENTE_CUENTA cc2, CUENTA cu
       WHERE cc2.cod_cliente = c.cod_cliente AND cc2.cod_cuenta = cu.cod_cuenta
      ) >
      (SELECT AVG(saldo) FROM CUENTA);

-- 20.  Clientes cuyo seguro más caro supera la media de precios de todos los seguros --
SELECT DISTINCT s.cod_cliente, MAX(s.precio) AS precio_max
FROM SEGURO s
GROUP BY s.cod_cliente
HAVING MAX(s.precio) > (
  SELECT AVG(precio)
  FROM SEGURO
);

--  21. Clientes cuyo total asegurado supera el 20% del saldo total de sus cuentas --
SELECT c.cod_cliente, c.nombre, c.apellidos
FROM CLIENTE c
WHERE (
  SELECT SUM(s.precio)
  FROM SEGURO s
  WHERE s.cod_cliente = c.cod_cliente
) > (
  SELECT SUM(cu.saldo) * 0.2
  FROM CLIENTE_CUENTA cc, CUENTA cu
  WHERE cc.cod_cliente = c.cod_cliente
    AND cc.cod_cuenta = cu.cod_cuenta
);

-- 22. Cuentas que han tenido transacciones en los últimos 5 años y con saldo superior a 1,000
SELECT cu.cod_cuenta, cu.saldo
FROM CUENTA cu
WHERE cu.saldo > 1000
  AND EXISTS (
    SELECT 1
    FROM TRANSACCION t
    WHERE (t.cuenta_origen = cu.cod_cuenta OR t.cuenta_destino = cu.cod_cuenta)
      AND t.fecha > SYSDATE - 365 * 5
);

-- 23. Clientes que tienen un seguro con precio superior al promedio de los precios de los seguros de tipo "Salud" --
SELECT c.dni, c.nombre, c.apellidos
FROM CLIENTE c
WHERE EXISTS (
    SELECT 1
    FROM SEGURO s
    WHERE s.cod_cliente = c.cod_cliente
    AND s.precio > (
        SELECT AVG(s2.precio)
        FROM SEGURO s2
        WHERE s2.tipo_cobertura = 'Salud'
    )
);

-- 24. Cuentas que no tienen transacciones en los últimos 6 meses pero tienen saldo superior a 3000 --
SELECT cu.cod_cuenta
FROM CUENTA cu
WHERE cu.saldo > 3000
AND cu.cod_cuenta NOT IN (
    SELECT t.cuenta_origen
    FROM TRANSACCION t
    WHERE t.fecha > SYSDATE - 180
    UNION
    SELECT t.cuenta_destino
    FROM TRANSACCION t
    WHERE t.fecha > SYSDATE - 180
);

-- 25. Cuentas con saldo superior a 2000 que no han sido asociadas a ningún cliente premium --
SELECT cu.cod_cuenta, cu.saldo
FROM CUENTA cu
WHERE cu.saldo > 2000
AND cu.cod_cuenta NOT IN (
    SELECT cc.cod_cuenta
    FROM CLIENTE_CUENTA cc, CLIENTE c
    WHERE cc.cod_cliente = c.cod_cliente
    AND c.tipo_cliente = 'PREMIUM'
);
