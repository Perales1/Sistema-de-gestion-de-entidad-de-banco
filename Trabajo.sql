-- 1. Saldo estimado si el interés en todos los clientes fuese de un 5% --
SELECT c.dni, cu.cod_cuenta, (cu.saldo * 0.05) AS interes_estimado
FROM CLIENTE c, CLIENTE_CUENTA cc, CUENTA cu
WHERE c.cod_cliente = cc.cod_cliente AND cc.cod_cuenta = cu.cod_cuenta;

-- 2. Primer cliente del banco --
SELECT c.dni, c.nombre, c.apellidos, cu.cod_cuenta AS "IBAN CUENTA", cu.fecha_apertura AS "Fecha Apertura"
FROM CLIENTE c, CLIENTE_CUENTA cc, CUENTA cu
WHERE c.cod_cliente = cc.cod_cliente AND cc.cod_cuenta = cu.cod_cuenta
  AND cu.fecha_apertura = (
    SELECT MIN(cu2.fecha_apertura)
    FROM CUENTA cu2
);

-- 3. Cliente con mas cantidad de cuentas--
SELECT c.cod_cliente, c.dni, c.nombre, COUNT(*) AS num_cuentas
FROM CLIENTE c, CLIENTE_CUENTA cc
WHERE c.cod_cliente = cc.cod_cliente
GROUP BY c.cod_cliente, c.dni, c.nombre
HAVING COUNT(*) = (
  SELECT MAX(cuenta_total)
  FROM (
    SELECT COUNT(*) AS cuenta_total
    FROM CLIENTE_CUENTA
    GROUP BY cod_cliente
  )
);

-- 4. Cuentas con movimientos por encima de la media --
SELECT t.cuenta_origen, COUNT(*) AS num_movimientos
FROM TRANSACCION t
GROUP BY t.cuenta_origen
HAVING COUNT(*) > (
  SELECT AVG(num_mov)
  FROM (
    SELECT COUNT(*) AS num_mov
    FROM TRANSACCION
    GROUP BY cuenta_origen
  )
);

-- 5. Sucursal con mas cuentas --
SELECT c.cod_sucursal AS "Sucursal", COUNT(*) AS num_cuentas
FROM CLIENTE_CUENTA cc, CUENTA c
WHERE cc.cod_cuenta = c.cod_cuenta
GROUP BY c.cod_sucursal
HAVING COUNT(*) = (
  SELECT MAX(num_cuentas)
  FROM (
    SELECT COUNT(*) AS num_cuentas
    FROM CLIENTE_CUENTA cc2, CUENTA c2
    WHERE cc2.cod_cuenta = c2.cod_cuenta
    GROUP BY c2.cod_sucursal
  )
);

-- 6. Cuentas con saldo por encima de la media --
SELECT c.cod_cuenta AS "IBAN CUENTA", c.saldo
FROM CUENTA c
WHERE c.saldo > (
  SELECT AVG(c2.saldo)
  FROM CUENTA c2
);

-- 7. Cuenta con menor saldo --
SELECT c.cod_cuenta, c.saldo
FROM CUENTA c
WHERE c.saldo = (
  SELECT MIN(saldo)
  FROM CUENTA
);

-- 8. Mayor cobro a una cuenta por transaccion --
SELECT t.cuenta_origen, t.cantidad
FROM TRANSACCION t
WHERE t.cantidad = (
  SELECT MIN(cantidad)
  FROM TRANSACCION
);

-- 9. Cuenta con mas tarjetas --
SELECT t.cod_cuenta, COUNT(*) AS num_tarjetas
FROM TARJETA t
GROUP BY t.cod_cuenta
HAVING COUNT(*) = (
    SELECT MAX(num_tarjetas)
    FROM (
        SELECT COUNT(*) AS num_tarjetas
        FROM TARJETA
        GROUP BY cod_cuenta
    )
);

-- 10. Total de seguros por tipo de cobertura y precio medio --
SELECT TIPO_COBERTURA, COUNT(*) AS NUM_SEGUROS, ROUND(AVG(PRECIO), 2) AS PRECIO_MEDIO
FROM SEGURO
GROUP BY TIPO_COBERTURA
HAVING AVG(PRECIO) > 100;

-- 11. Clientes con seguros más caros que la media --
SELECT COD_CLIENTE, PRECIO
FROM SEGURO
WHERE PRECIO > (
    SELECT AVG(PRECIO)
    FROM SEGURO
);

-- 12. Clientes con al menos 7 transacciones con tarjeta --
SELECT 
    C.NOMBRE, 
    C.APELLIDOS, 
    COUNT(T.COD_TRANSACCION) AS NUM_TRANSACCIONES
FROM CLIENTE C, CLIENTE_CUENTA CC, TRANSACCION T, CUENTA CU
WHERE C.COD_CLIENTE = CC.COD_CLIENTE
  AND CC.COD_CUENTA = CU.COD_CUENTA
  AND (CU.COD_CUENTA = T.CUENTA_ORIGEN OR CU.COD_CUENTA = T.CUENTA_DESTINO)
GROUP BY C.NOMBRE, C.APELLIDOS
HAVING COUNT(T.COD_TRANSACCION) > 7;

-- 13. Nombre y edad de los empleados con un salario superior a 22700 --
SELECT NOMBRE, APELLIDOS, ROUND(MONTHS_BETWEEN(SYSDATE, FECHA_NACIMIENTO)/12, 1) AS EDAD
FROM EMPLEADO
WHERE SALARIO > 22700;

-- 14. Empleados que trabajan en la misma localidad donde vive algún cliente --
SELECT 
    E.NOMBRE AS NOMBRE_EMPLEADO,
