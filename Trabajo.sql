-- CREACIÓN DE VISTAS --
-- Vista 1: Clientes y número de seguros contratados --
CREATE VIEW vista_clientes_seguros AS
SELECT
    C.COD_CLIENTE,
    C.NOMBRE,
    C.APELLIDOS,
    (
        SELECT COUNT(*)
        FROM SEGURO S
        WHERE S.COD_CLIENTE = C.COD_CLIENTE
    ) AS NUM_SEGUROS
FROM CLIENTE C;

-- Vista 2: Empleados con nombre de sucursal y salario --
CREATE VIEW vista_empleados_sucursal AS
SELECT
    E.COD_SUCURSAL,
    (
        SELECT NOMBRE
        FROM SUCURSAL S
        WHERE S.COD_SUCURSAL = E.COD_SUCURSAL
    ) AS NOMBRE_SUCURSAL,
    E.NOMBRE AS NOMBRE_EMPLEADO,
    E.APELLIDOS,
    E.SALARIO
FROM EMPLEADO E;

-- Vista 3: Clientes y el saldo total de sus cuentas
CREATE VIEW vista_clientes_saldo AS
SELECT
    C.COD_CLIENTE,
    C.NOMBRE,
    C.APELLIDOS,
    (
        SELECT SUM(CU.SALDO)
        FROM CUENTA CU
        WHERE CU.COD_CUENTA IN (
            SELECT CC.COD_CUENTA
            FROM CLIENTE_CUENTA CC
            WHERE CC.COD_CLIENTE = C.COD_CLIENTE
        )
    ) AS TOTAL_SALDO
FROM CLIENTE C;

-- Vista 4: Empleados y los clientes de su sucursal
CREATE VIEW vista_empleados_clientes AS
SELECT
    E.COD_EMPLEADO,
    E.NOMBRE AS NOMBRE_EMPLEADO,
    E.APELLIDOS AS APELLIDOS_EMPLEADO,
    C.COD_CLIENTE,
    C.NOMBRE AS NOMBRE_CLIENTE,
    C.APELLIDOS AS APELLIDOS_CLIENTE
FROM EMPLEADO E, CLIENTE C
WHERE C.COD_LOCALIDAD = E.COD_LOCALIDAD;

