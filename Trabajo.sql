-- CREACIÓN DE LOCALIDAD --
CREATE TABLE LOCALIDAD (
    COD_LOCALIDAD NUMBER,
    LOCALIDAD VARCHAR(100) CONSTRAINT nn_nombre_loc NOT NULL,
    CONSTRAINT pk_localidad PRIMARY KEY (COD_LOCALIDAD)
);

-- CREACIÓN DE SUCURSAL --
CREATE TABLE SUCURSAL (
    COD_SUCURSAL VARCHAR(4),
    COD_LOCALIDAD NUMBER,
    TELEFONO VARCHAR(15),
    NOMBRE VARCHAR(50),
    EMAIL VARCHAR(100),
    CONSTRAINT pk_sucursal PRIMARY KEY (COD_SUCURSAL),
    CONSTRAINT fk_sucursal_localidad FOREIGN KEY (COD_LOCALIDAD) REFERENCES LOCALIDAD
);

-- CREACIÓN DE EMPLEADO --
CREATE TABLE EMPLEADO (
    COD_EMPLEADO NUMBER,
    DNI VARCHAR(9) CONSTRAINT nn_dni_emp NOT NULL,
    NOMBRE VARCHAR(50),
    APELLIDOS VARCHAR(100),
    TELEFONO VARCHAR(15),
    EMAIL VARCHAR(100),
    SALARIO DECIMAL CONSTRAINT chk_salario_emp CHECK (SALARIO > 0),
    COD_SUCURSAL VARCHAR(4),
    PUESTO VARCHAR(50),
    FECHA_NACIMIENTO DATE,
    COD_LOCALIDAD NUMBER,
    CONSTRAINT pk_empleado PRIMARY KEY (COD_EMPLEADO),
    CONSTRAINT fk_empleado_sucursal FOREIGN KEY (COD_SUCURSAL) REFERENCES SUCURSAL,
    CONSTRAINT fk_empleado_localidad FOREIGN KEY (COD_LOCALIDAD) REFERENCES LOCALIDAD
);

-- CREACIÓN DE CLIENTE --
CREATE TABLE CLIENTE (
    COD_CLIENTE NUMBER,
    DNI VARCHAR(9) CONSTRAINT nn_dni_cli NOT NULL,
    NOMBRE VARCHAR(50),
    APELLIDOS VARCHAR(100),
    TELEFONO VARCHAR(15),
    EMAIL VARCHAR(100),
    COD_LOCALIDAD NUMBER,
    TIPO_CLIENTE VARCHAR(20) CONSTRAINT chk_tipo_cli CHECK (TIPO_CLIENTE IN ('NORMAL', 'PREMIUM')),
    CONSTRAINT pk_cliente PRIMARY KEY (COD_CLIENTE),
    CONSTRAINT fk_cliente_localidad FOREIGN KEY (COD_LOCALIDAD) REFERENCES LOCALIDAD
);

-- CREACIÓN DE SEGURO --
CREATE TABLE SEGURO (
    COD_SEGURO NUMBER,
    COD_CLIENTE NUMBER,
    TIPO_COBERTURA VARCHAR(50),
    PRECIO DECIMAL CONSTRAINT chk_precio CHECK (PRECIO > 0),
    FECHA_INICIO DATE,
    FECHA_EXPIRACION DATE,
    BIENES_ASEGURADOS VARCHAR(100),
    CONSTRAINT pk_seguro PRIMARY KEY (COD_SEGURO),
    CONSTRAINT fk_seguro_cliente FOREIGN KEY (COD_CLIENTE) REFERENCES CLIENTE
);

-- CREACIÓN DE PRESTAMO --
CREATE TABLE PRESTAMO (
    COD_PRESTAMO NUMBER CONSTRAINT pk_prestamo PRIMARY KEY, 
    COD_CUENTA VARCHAR(24) CONSTRAINT nn_cod_cuenta NOT NULL,
    IMPORTE NUMBER(15, 2) CONSTRAINT nn_importe NOT NULL,
    PLAZO NUMBER CONSTRAINT nn_plazo NOT NULL,
    INTERES NUMBER(5, 2) CONSTRAINT nn_interes NOT NULL,
    TIPO_INTERES VARCHAR(10) CONSTRAINT nn_tipo_interes NOT NULL,
    CONSTRAINT fk_prestamo_cuenta FOREIGN KEY (COD_CUENTA) REFERENCES CUENTA(COD_CUENTA)
);

-- CREACIÓN DE TARJETA --
CREATE TABLE TARJETA (
    COD_TARJETA NUMBER CONSTRAINT pk_tarjeta PRIMARY KEY,
    TIPO VARCHAR(10) CONSTRAINT nn_tipo_tarjeta NOT NULL,
    FECHA_EXPIRACION DATE,
    COD_CUENTA VARCHAR(24) CONSTRAINT nn_cod_cuenta_tarjeta NOT NULL,
    NOMBRE VARCHAR(15) CONSTRAINT nn_nombre_tarjeta NOT NULL,
    CONSTRAINT fk_tarjeta_cuenta FOREIGN KEY (COD_CUENTA) REFERENCES CUENTA(COD_CUENTA)
);

-- CREACIÓN DE FACTURA --
CREATE TABLE FACTURA (
    COD_FACTURA NUMBER CONSTRAINT pk_factura PRIMARY KEY,
    FECHA DATE
);

-- CREACIÓN DE TRANSACCION --
CREATE TABLE TRANSACCION (
    COD_TRANSACCION NUMBER CONSTRAINT pk_transaccion PRIMARY KEY,
    FECHA DATE,
    CANTIDAD NUMBER(15, 2) CONSTRAINT nn_cantidad_transaccion NOT NULL,
    TIPO VARCHAR(20),
    CUENTA_ORIGEN VARCHAR(24) CONSTRAINT nn_cuenta_origen_transaccion NOT NULL,
    CUENTA_DESTINO VARCHAR(24) CONSTRAINT nn_cuenta_destino_transaccion NOT NULL,
    COD_TARJETA NUMBER CONSTRAINT nn_cod_tarjeta_transaccion NOT NULL,
    CONSTRAINT fk_transaccion_tarjeta FOREIGN KEY (COD_TARJETA) REFERENCES TARJETA(COD_TARJETA),
    CONSTRAINT fk_transaccion_cuenta_origen FOREIGN KEY (CUENTA_ORIGEN) REFERENCES CUENTA(COD_CUENTA),
    CONSTRAINT fk_transaccion_cuenta_destino FOREIGN KEY (CUENTA_DESTINO) REFERENCES CUENTA(COD_CUENTA)
);

-- CREACIÓN DE TRANSACCION_FACTURA --
CREATE TABLE TRANSACCION_FACTURA (
    COD_TRANSACCION NUMBER,
    COD_FACTURA NUMBER,
    CONSTRAINT pk_transaccion_factura PRIMARY KEY (COD_TRANSACCION, COD_FACTURA),
    FOREIGN KEY (COD_FACTURA) REFERENCES FACTURA(COD_FACTURA),
    FOREIGN KEY (COD_TRANSACCION) REFERENCES TRANSACCION(COD_TRANSACCION)
);

-- CREACIÓN DE CUENTA --
CREATE TABLE CUENTA (
    COD_CUENTA VARCHAR(24) PRIMARY KEY,
    TIPO_CUENTA VARCHAR(12),
    SALDO DECIMAL(15, 2),
    FECHA_APERTURA DATE,
    COD_SUCURSAL VARCHAR(4),
    CONSTRAINT ck_cod_cuenta_iban CHECK (COD_CUENTA LIKE 'ES%'),
    CONSTRAINT fk_cuenta_sucursal FOREIGN KEY (COD_SUCURSAL) REFERENCES SUCURSAL(COD_SUCURSAL)
);

-- CREACIÓN DE CLIENTE_CUENTA --
CREATE TABLE CLIENTE_CUENTA (
    COD_CUENTA VARCHAR(24),
    COD_CLIENTE NUMBER,
    PRIMARY KEY (COD_CUENTA, COD_CLIENTE),
    FOREIGN KEY (COD_CUENTA) REFERENCES CUENTA(COD_CUENTA),
    FOREIGN KEY (COD_CLIENTE) REFERENCES CLIENTE(COD_CLIENTE)
);

